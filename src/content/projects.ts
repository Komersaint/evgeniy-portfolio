export type ProjectLink = {
  label: string;
  href: string;
  external?: boolean;
};

export type Project = {
  slug: string;
  title: string;
  kicker: string;
  summary: string;
  /** Статус: краткая честная формулировка. */
  status: string;
  /** Короткий номер для списка, например «01». */
  index: string;
  image?: string;
  imageAlt?: string;
  /** Моя роль в проекте. */
  role: string;
  /** Постановка задачи: с чего начиналось. */
  problem: string;
  /** Что делал по шагам. */
  actions: string[];
  /** Что получилось / что подтверждаемо. */
  result: string;
  /** Технологии и инструменты. */
  stack: string[];
  /** Отдельные подтверждаемые факты — короткий список. */
  facts?: { label: string; value: string }[];
  /** Честная пометка: чего пока нет. */
  statusNote?: string;
  links?: ProjectLink[];
  /** Показывать в блоке «Направления автоматизации». */
  kind: 'case' | 'direction' | 'product';
};

